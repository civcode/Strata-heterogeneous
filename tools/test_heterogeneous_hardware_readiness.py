#!/usr/bin/env python3
"""M2.7 read-only hardware assessment contract tests (all fake sysfs/procfs)."""
from __future__ import annotations

import hashlib
import io
import json
from pathlib import Path
import tempfile
import unittest
from contextlib import redirect_stdout, redirect_stderr

import heterogeneous_hardware_readiness as hw


class ReadinessTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="hetero-m27-")
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.sys = self.root / "sys"
        self.proc = self.root / "proc"
        (self.sys / "bus/pci/devices").mkdir(parents=True)
        (self.proc / "driver/nvidia").mkdir(parents=True)
        (self.sys / "module/nvidia").mkdir(parents=True)
        (self.sys / "module/nvidia/version").write_text("555.10\n")
        (self.proc / "modules").write_text("nvidia 1 0 - Live 0x0\namdgpu 1 0 - Live 0x0\n")
        self.make_gpu("0000:01:00.0", "0x10de", "nvidia", "0x2702", "card0")
        self.make_gpu("0000:41:00.0", "0x1002", "amdgpu", "0x75a1", "card1")
        self.make_gpu("0000:81:00.0", "0x1002", "amdgpu", "0x75a1", "card2")
        self.pack = self.root / "pack"
        self.pack.mkdir()
        self.write_pack()
        self.cfg = []
        for i, (start, end, ordinal) in enumerate(((0, 12, 0), (12, 30, 0), (30, 48, 1))):
            file = self.root / f"stage-{i}.cfg"
            file.write_text("".join(f"{k}={v}\n" for k, v in dict(
                version=2, stage_index=i, first_layer=start, end_layer=end,
                device_ordinal=ordinal, n_layers=48, hc=4, n_embd=2560, n_vocab=248320,
                model_fingerprint=2026111301, pack_dir=self.pack,
                profile_path=self.root / "expert-profile.bin",
                gguf_shards="/tmp/one.gguf;/tmp/two.gguf",
                index_sha256=hashlib.sha256((self.pack / "index.txt").read_bytes()).hexdigest(),
                max_cache_slots=16, max_cells=2048, max_t=8,
                free_reserve_bytes=536870912, arena_budget_bytes=0).items()))
            self.cfg.append(file)
        self.plan = "cuda:0:0-12,hip:0:12-30,hip:1:30-48"
        self.bind = ["cuda:0=0000:01:00.0", "hip:0=0000:41:00.0", "hip:1=0000:81:00.0"]

    def make_gpu(self, bdf, vendor, driver, dev_id, card):
        dest = self.sys / "bus/pci/devices" / bdf
        dest.mkdir(parents=True)
        (dest / "vendor").write_text(vendor)
        (dest / "device").write_text(dev_id)
        (dest / "class").write_text("0x030000\n")
        (dest / "numa_node").write_text("0\n")
        drv = self.sys / "bus/pci/drivers" / driver
        drv.mkdir(parents=True, exist_ok=True)
        (dest / "driver").symlink_to(drv)
        (dest / "drm").mkdir()
        (dest / "drm" / card).mkdir()

    def write_pack(self):
        lines = ["# generated by tools/pack_index.py", "# align 256 pool 65536 tensors 49",
                 "# name ..."]
        # One global weight is replicated in all three compact stage arenas.
        for n in range(-1, 48):
            name = "output.weight" if n == -1 else f"blk.{n}.weight"
            off = (n + 1) * 256
            fields = [0, 0, 0, 128, off, 128, 2560, 2560] + [0] * 10
            lines.append(name + " " + " ".join(map(str, fields)))
        (self.pack / "index.txt").write_text("\n".join(lines) + "\n")
        with (self.pack / "experts.bin").open("wb") as f:
            f.truncate(1024)  # M2.7 needs only file existence; never reads expert data

    def assess(self, bindings=None, log=None):
        return hw.assess(self.plan, 48, self.cfg, self.sys, self.proc,
                         self.bind if bindings is None else bindings, log)

    def test_enumeration_and_driver(self):
        pci = hw.gpu_inventory(self.sys)
        self.assertEqual(3, len(pci))
        self.assertEqual(["nvidia", "amd", "amd"], [d["vendor"] for d in pci])
        self.assertEqual("nvidia", pci[0]["bound_driver"])
        self.assertEqual(["card0"], pci[0]["drm_cards"])
        self.assertEqual(["amdgpu", "nvidia"], hw.driver_inventory(self.sys, self.proc)["loaded_modules"])

    def test_passive_assessment_unverified(self):
        doc = self.assess()
        self.assertTrue(doc["passive_only"])
        self.assertFalse(doc["runtime_initialized"])
        self.assertEqual("UNVERIFIED", doc["readiness"])
        self.assertEqual([], doc["blockers"])
        self.assertFalse(any(m["runtime_ordinal_confirmed"] for m in doc["ordinal_declarations"]))

    def test_default_no_binding_is_not_an_hardware_failure(self):
        doc = self.assess([])
        self.assertEqual("UNVERIFIED", doc["readiness"])
        self.assertEqual([], doc["blockers"])
        self.assertTrue(all(x["declared_bdf"] is None for x in doc["ordinal_declarations"]))
        self.assertTrue(all(x["runtime_ordinal_confirmed"] is False
                            for x in doc["ordinal_declarations"]))

    def test_memory_selection(self):
        memory = hw.planned_memory(self.plan, self.cfg, 48)
        self.assertEqual([13 * 256, 19 * 256, 19 * 256],
                         [m["selected_pack_weight_bytes"] for m in memory])
        self.assertEqual(16 * 1_382_400 + 98304,
                         memory[0]["canonical_expert_cache_plus_table_bytes"])
        self.assertGreater(memory[0]["known_allocations_plus_reserve_bytes"],
                           memory[0]["known_allocations_floor_bytes"])
        self.assertIn("stage session arena (core::session_bytes)", memory[0]["unaccounted"])

    def test_zero_slots_uncapped(self):
        self.cfg[0].write_text(self.cfg[0].read_text().replace("max_cache_slots=16", "max_cache_slots=0"))
        mem = hw.planned_memory(self.plan, self.cfg, 48)
        self.assertEqual(12 * 512, mem[0]["configured_expert_slots"])

    def test_cross_stage_index_hash_mismatch(self):
        self.cfg[0].write_text(self.cfg[0].read_text().replace("index_sha256=", "index_sha256=0"))
        with self.assertRaises(ValueError):
            hw.planned_memory(self.plan, self.cfg, 48)

    def test_file_hash_tamper(self):
        (self.pack / "index.txt").write_text((self.pack / "index.txt").read_text() + "# tamper\n")
        with self.assertRaisesRegex(ValueError, "SHA-256"):
            hw.planned_memory(self.plan, self.cfg, 48)

    def test_mismatched_stage_identity(self):
        self.cfg[1].write_text(self.cfg[1].read_text().replace("device_ordinal=0", "device_ordinal=1"))
        with self.assertRaisesRegex(ValueError, "ordinal"):
            hw.planned_memory(self.plan, self.cfg, 48)

    def test_noncanonical_native_pack_rejected(self):
        (self.pack / "native_experts.txt").write_text("native")
        with self.assertRaisesRegex(ValueError, "canonical"):
            hw.planned_memory(self.plan, self.cfg, 48)

    def test_wrong_vendor_binding(self):
        bindings = ["cuda:0=0000:41:00.0", "hip:0=0000:01:00.0", "hip:1=0000:81:00.0"]
        doc = self.assess(bindings)
        self.assertEqual("BLOCKED", doc["readiness"])
        self.assertTrue(any("vendor mismatch" in e for e in doc["blockers"]))

    def test_repeated_device_binding(self):
        bindings = ["cuda:0=0000:01:00.0", "hip:0=0000:41:00.0", "hip:1=0000:41:00.0"]
        self.assertTrue(any("multiple" in e for e in self.assess(bindings)["blockers"]))

    def test_malformed_mapping_syntax(self):
        doc = self.assess(["cuda:0=not-a-bdf"])
        self.assertEqual("BLOCKED", doc["readiness"])
        self.assertTrue(any("invalid --bind syntax" in e for e in doc["blockers"]))

    def test_index_row_before_header_rejected(self):
        index = self.pack / "index.txt"
        index.write_text("output.weight 0 0 0 128 0 128 2560 2560 " + "0 " * 9 + "0\n" +
                         index.read_text())
        # Also update the checksum: a parsing error, not a digest error.
        digest = hashlib.sha256(index.read_bytes()).hexdigest()
        for cfg in self.cfg:
            cfg.write_text(cfg.read_text().replace(
                cfg.read_text().split("index_sha256=")[1].splitlines()[0], digest))
        with self.assertRaisesRegex(ValueError, "before pack index header"):
            hw.planned_memory(self.plan, self.cfg, 48)

    def test_unavailable_sysfs_fails_without_driver_touch(self):
        with self.assertRaisesRegex(ValueError, "PCI sysfs root unavailable"):
            hw.gpu_inventory(self.root / "nonexistent")

    def test_wrong_driver(self):
        (self.sys / "bus/pci/devices/0000:41:00.0/driver").unlink()
        doc = self.assess()
        self.assertTrue(any("driver not bound" in e for e in doc["blockers"]))

    def test_pci_count_short(self):
        node = self.sys / "bus/pci/devices/0000:81:00.0"
        (node / "vendor").write_text("0x8086")
        doc = self.assess()
        self.assertTrue(any("fewer AMD" in e for e in doc["blockers"]))

    def test_preexported_log(self):
        logfile = self.root / "exported-kernel-log.txt"
        logfile.write_text("unrelated boot output\nNVRM: Xid (PCI:0000:01:00): 79, GPU has fallen off the bus\n")
        data = hw.scan_preexported_log(logfile)
        self.assertEqual(1, len(data["fault_markers"]))
        empty = self.root / "empty.log"
        empty.write_text("")
        self.assertEqual([], hw.scan_preexported_log(empty)["fault_markers"])

    def test_log_not_read_by_default(self):
        self.assertIsNone(self.assess()["offline_kernel_log"]["fault_markers"])

    def test_cli_json_and_blocker_exit(self):
        params = ["--plan", self.plan, "--sysfs-root", str(self.sys),
                  "--procfs-root", str(self.proc), "--json"]
        for cfg in self.cfg:
            params.extend(["--config", str(cfg)])
        with redirect_stdout(io.StringIO()) as out, redirect_stderr(io.StringIO()):
            code = hw.main(params)
        self.assertEqual(0, code)  # no optional binding is not a PCI fault
        self.assertEqual("UNVERIFIED", json.loads(out.getvalue())["readiness"])
        for b in self.bind:
            params.extend(["--bind", b])
        with redirect_stdout(io.StringIO()) as out, redirect_stderr(io.StringIO()):
            code = hw.main(params)
        self.assertEqual(0, code)
        self.assertEqual("UNVERIFIED", json.loads(out.getvalue())["readiness"])
        params.extend(["--bind", "hip:0=0000:01:00.0"])
        with redirect_stdout(io.StringIO()) as out, redirect_stderr(io.StringIO()):
            code = hw.main(params)
        self.assertEqual(1, code)
        self.assertEqual("BLOCKED", json.loads(out.getvalue())["readiness"])


if __name__ == "__main__":
    unittest.main()
